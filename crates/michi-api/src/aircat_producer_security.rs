//! AirCat original-asset grant/snapshot admission controller (A30).
//!
//! Instantiate once in AppState, never in an untrusted request. The caller
//! MUST verify the requesting Home member and its cryptographic possession
//! before invoking reserve_authorization(); an old Link bearer UUID alone is
//! not such proof. No background timers, polling, scanning or extra identities.
//!
//! The only resources held here are a bounded nonce ledger and immutable
//! producer-generated manifest snapshots, both pruned lazily on requests.

use crate::aircat_grants::{manifest_sha256, Manifest, Refusal, Request};
use crate::aircat_original_file::expected_strong_etag;
use base64::{engine::general_purpose::URL_SAFE_NO_PAD, Engine};
use std::collections::{HashMap, HashSet};
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::Mutex;

const MAX_ACTIVE: usize = 1024;
const MAX_REPLAY_NONCES: usize = 4096;
const MAX_LIFETIME_MS: i64 = 600_000;
const MAX_DIGEST_CACHE: usize = 10_000;

#[derive(Clone, Debug)]
pub struct OriginalAssetRevision {
    pub remote_track_id: String,
    pub exact_size: i64,
    pub exact_sha256: String,
    /// Quoted strong revision, established from immutable original bytes.
    pub strong_etag: String,
    /// Device + inode pair on POSIX filesystems to detect file swaps of equal size.
    pub dev_ino: Option<(u64, u64)>,
    /// Modification timestamp in nanoseconds since UNIX_EPOCH.
    pub modified_unix_ns: Option<i128>,
}

#[derive(Clone, Debug)]
pub struct ProducerSnapshot {
    pub manifest: Manifest,
    pub manifest_sha256: String,
    pub authenticated_destination_michi_id: String,
    pub expires_at_ms: i64,
    pub originals: Vec<OriginalAssetRevision>,
}

#[derive(Clone, Debug)]
struct HomeAuthChallengeEntry {
    client_michi_id: String,
    nonce: String,
    expires_at_ms: i64,
}

#[derive(Clone, Debug, serde::Serialize)]
pub struct AirCatStatsSnapshot {
    pub active_snapshots: usize,
    pub active_home_sessions: usize,
    pub cached_digests: usize,
    pub revoked_members_cached: usize,
    pub downloads_started: u64,
    pub bytes_served: u64,
    pub digest_cache_hits: u64,
    pub midstream_revocations: u64,
    pub tls_rejections: u64,
}

#[derive(Default, Debug)]
struct Inner {
    /// key: (destination Michi ID, canonical base64url nonce)
    nonces: HashMap<(String, String), i64>,
    /// key: (transfer ID, exact SHA-256 canonical manifest)
    snapshots: HashMap<(String, String), ProducerSnapshot>,
    /// key: challenge UUID for HOME_MEMBERSHIP mutual auth
    home_challenges: HashMap<uuid::Uuid, HomeAuthChallengeEntry>,
    /// key: opaque bearer token -> (verified client_michi_id, expires_at_ms)
    home_sessions: HashMap<String, (String, i64)>,
    /// key: remote_track_id -> verified original file revision matched by (size, dev_ino, mtime_ns)
    digest_cache: HashMap<String, OriginalAssetRevision>,
    /// in-memory set of revoked member IDs for zero-SQLite chunk-boundary abort
    revoked_members: HashSet<String>,
}

#[derive(Default, Debug)]
pub struct AirCatProducerSecurityState {
    inner: Mutex<Inner>,
    downloads_started: AtomicU64,
    bytes_served: AtomicU64,
    digest_cache_hits: AtomicU64,
    midstream_revocations: AtomicU64,
    tls_rejections: AtomicU64,
}

impl AirCatProducerSecurityState {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn has_snapshot(&self, transfer_id: &str, manifest_sha: &str) -> bool {
        if let Ok(inner) = self.inner.lock() {
            inner
                .snapshots
                .contains_key(&(transfer_id.to_string(), manifest_sha.to_string()))
        } else {
            false
        }
    }

    /// Store ONLY a manifest generated by reading producer-controlled original
    /// assets, under the caller's established Home member identity. Never store
    /// the untrusted client manifest as the source of truth.
    pub fn record_producer_snapshot(
        &self,
        snapshot: ProducerSnapshot,
        now_ms: i64,
    ) -> Result<(), Refusal> {
        if now_ms <= 0
            || snapshot.authenticated_destination_michi_id.is_empty()
            || snapshot
                .manifest
                .items
                .iter()
                .map(|i| &i.remote_track_id)
                .collect::<std::collections::HashSet<_>>()
                .len()
                != snapshot.manifest.items.len()
            || snapshot.expires_at_ms <= now_ms
            || snapshot.expires_at_ms - now_ms > MAX_LIFETIME_MS
            || snapshot.manifest_sha256 != manifest_sha256(&snapshot.manifest)?
            || snapshot.originals.len() != snapshot.manifest.items.len()
            || !snapshot.manifest.items.iter().all(|i| {
                snapshot
                    .originals
                    .iter()
                    .filter(|o| {
                        o.remote_track_id == i.remote_track_id
                            && o.exact_size == i.size
                            && o.exact_sha256.eq_ignore_ascii_case(&i.sha256)
                            && expected_strong_etag(&i.sha256.to_ascii_lowercase(), i.size)
                                .map(|et| et == o.strong_etag)
                                .unwrap_or(false)
                    })
                    .count()
                    == 1
            })
        {
            return Err(Refusal::NotOriginalBytes);
        }
        let mut inner = self.inner.lock().map_err(|_| Refusal::InvalidFields)?;
        Self::prune(&mut inner, now_ms);
        let key = (
            snapshot.manifest.transfer_id.clone(),
            snapshot.manifest_sha256.clone(),
        );
        if inner.snapshots.contains_key(&key) || inner.snapshots.len() >= MAX_ACTIVE {
            return Err(Refusal::InvalidFields);
        }
        inner.snapshots.insert(key, snapshot);
        Ok(())
    }

    /// Reserve the exact client challenge for the authenticated member; return
    /// an immutable producer snapshot ONLY if the client request is an exact
    /// copy of the authorized original catalog. Sign AFTER this succeeds.
    /// A second attempt with the same (member, nonce) fails even with identical
    /// contents. Crash/restart clears the ledger and grant sessions; producer
    /// must reject old grants without their retained snapshot.
    pub fn reserve_authorization(
        &self,
        req: &Request,
        authenticated_member: &str,
        now_ms: i64,
    ) -> Result<ProducerSnapshot, Refusal> {
        if now_ms <= 0
            || authenticated_member.is_empty()
            || req.intent.destination_michi_id != authenticated_member
            || req.intent.source_michi_id != req.manifest.source_device_id
            || req.intent.transfer_id != req.manifest.transfer_id
            || req.client_nonce_base64_url.is_empty()
            || !URL_SAFE_NO_PAD
                .decode(&req.client_nonce_base64_url)
                .map(|v| {
                    v.len() >= 16
                        && v.len() <= 64
                        && URL_SAFE_NO_PAD.encode(v) == req.client_nonce_base64_url
                })
                .unwrap_or(false)
            || req.manifest_sha256 != manifest_sha256(&req.manifest)?
        {
            return Err(Refusal::WrongAudience);
        }
        let mut inner = self.inner.lock().map_err(|_| Refusal::InvalidFields)?;
        Self::prune(&mut inner, now_ms);
        let key = (req.intent.transfer_id.clone(), req.manifest_sha256.clone());
        let snapshot = inner.snapshots.get(&key).ok_or(Refusal::NotOriginalBytes)?;
        if snapshot.expires_at_ms <= now_ms || snapshot.manifest.transfer_id != req.manifest.transfer_id ||
           snapshot.authenticated_destination_michi_id != authenticated_member ||
           snapshot.manifest_sha256 != req.manifest_sha256 ||
           // Canonical bytes also cover per-asset title/album/format and ordering.
           crate::aircat_grants::manifest_bytes(&snapshot.manifest)? !=
              crate::aircat_grants::manifest_bytes(&req.manifest)?
        {
            return Err(Refusal::WrongAudience);
        }
        let selected = snapshot.clone();
        if inner.nonces.len() >= MAX_REPLAY_NONCES
            || inner.nonces.contains_key(&(
                authenticated_member.to_owned(),
                req.client_nonce_base64_url.clone(),
            ))
        {
            return Err(Refusal::InvalidFields);
        }
        let expires = now_ms
            .checked_add(MAX_LIFETIME_MS)
            .ok_or(Refusal::Expired)?;
        inner.nonces.insert(
            (
                authenticated_member.to_owned(),
                req.client_nonce_base64_url.clone(),
            ),
            expires,
        );
        Ok(selected)
    }

    /// Before each authorized original HTTP GET/Range and at stream boundary.
    /// Caller also verifies signature, Home/ACL/revocation and the file descriptor
    /// revision rather than trusting only this in-memory receipt.
    pub fn selected_original(
        &self,
        transfer_id: &str,
        manifest_sha: &str,
        authenticated_member: &str,
        remote_id: &str,
        now_ms: i64,
    ) -> Result<OriginalAssetRevision, Refusal> {
        let mut inner = self.inner.lock().map_err(|_| Refusal::InvalidFields)?;
        Self::prune(&mut inner, now_ms);
        let s = inner
            .snapshots
            .get(&(transfer_id.to_owned(), manifest_sha.to_owned()))
            .ok_or(Refusal::NotOriginalBytes)?;
        if s.authenticated_destination_michi_id != authenticated_member || s.expires_at_ms <= now_ms
        {
            return Err(Refusal::WrongAudience);
        }
        let mut matched = s
            .originals
            .iter()
            .filter(|x| x.remote_track_id == remote_id);
        let original = matched.next().ok_or(Refusal::NotOriginalBytes)?;
        if matched.next().is_some() {
            return Err(Refusal::NotOriginalBytes);
        }
        Ok(original.clone())
    }

    pub fn issue_home_challenge(
        &self,
        client_michi_id: &str,
        nonce: String,
        now_ms: i64,
        ttl_ms: i64,
    ) -> Result<uuid::Uuid, Refusal> {
        let mut inner = self.inner.lock().map_err(|_| Refusal::InvalidFields)?;
        Self::prune(&mut inner, now_ms);
        if inner.home_challenges.len() >= MAX_ACTIVE {
            return Err(Refusal::InvalidFields);
        }
        let id = uuid::Uuid::new_v4();
        inner.home_challenges.insert(
            id,
            HomeAuthChallengeEntry {
                client_michi_id: client_michi_id.to_string(),
                nonce,
                expires_at_ms: now_ms.saturating_add(ttl_ms),
            },
        );
        Ok(id)
    }

    pub fn consume_home_challenge(
        &self,
        challenge_id: &uuid::Uuid,
        client_michi_id: &str,
        now_ms: i64,
    ) -> Result<String, Refusal> {
        let mut inner = self.inner.lock().map_err(|_| Refusal::InvalidFields)?;
        Self::prune(&mut inner, now_ms);
        let entry = inner
            .home_challenges
            .remove(challenge_id)
            .ok_or(Refusal::Expired)?;
        if entry.expires_at_ms <= now_ms || entry.client_michi_id != client_michi_id {
            return Err(Refusal::WrongAudience);
        }
        Ok(entry.nonce)
    }

    pub fn record_home_session(
        &self,
        token: String,
        client_michi_id: String,
        now_ms: i64,
        ttl_ms: i64,
    ) {
        if let Ok(mut inner) = self.inner.lock() {
            Self::prune(&mut inner, now_ms);
            if inner.home_sessions.len() >= MAX_ACTIVE && !inner.home_sessions.contains_key(&token)
            {
                if let Some(evict_key) = inner
                    .home_sessions
                    .iter()
                    .min_by_key(|(_, (_, exp))| *exp)
                    .map(|(k, _)| k.clone())
                {
                    inner.home_sessions.remove(&evict_key);
                }
            }
            inner
                .home_sessions
                .insert(token, (client_michi_id, now_ms.saturating_add(ttl_ms)));
        }
    }

    pub fn lookup_home_session(&self, token: &str, now_ms: i64) -> Option<String> {
        let mut inner = self.inner.lock().ok()?;
        Self::prune(&mut inner, now_ms);
        inner
            .home_sessions
            .get(token)
            .filter(|(_, exp)| *exp > now_ms)
            .map(|(id, _)| id.clone())
    }

    pub fn cached_original_if_fresh(
        &self,
        remote_track_id: &str,
        meta: &std::fs::Metadata,
    ) -> Option<OriginalAssetRevision> {
        let rev = self
            .inner
            .lock()
            .ok()?
            .digest_cache
            .get(remote_track_id)
            .cloned()?;
        if rev.dev_ino.is_none() || rev.modified_unix_ns.is_none() {
            return None;
        }
        if crate::aircat_original_file::revision_matches_metadata(&rev, meta) {
            self.digest_cache_hits.fetch_add(1, Ordering::Relaxed);
            Some(rev)
        } else {
            None
        }
    }

    pub fn cache_original_revision(&self, rev: OriginalAssetRevision) {
        if let Ok(mut inner) = self.inner.lock() {
            if inner.digest_cache.len() >= MAX_DIGEST_CACHE
                && !inner.digest_cache.contains_key(&rev.remote_track_id)
            {
                if let Some(evict_key) = inner.digest_cache.keys().next().cloned() {
                    inner.digest_cache.remove(&evict_key);
                }
            }
            inner.digest_cache.insert(rev.remote_track_id.clone(), rev);
        }
    }

    pub fn is_member_revoked_in_memory(&self, member: &str) -> bool {
        self.inner
            .lock()
            .map(|inner| inner.revoked_members.contains(member))
            .unwrap_or(false)
    }

    pub fn record_download_started(&self) {
        self.downloads_started.fetch_add(1, Ordering::Relaxed);
    }

    pub fn record_bytes_served(&self, bytes: u64) {
        self.bytes_served.fetch_add(bytes, Ordering::Relaxed);
    }

    pub fn record_midstream_revocation(&self) {
        self.midstream_revocations.fetch_add(1, Ordering::Relaxed);
    }

    pub fn record_tls_rejection(&self) {
        self.tls_rejections.fetch_add(1, Ordering::Relaxed);
    }

    pub fn stats_snapshot(&self, now_ms: i64) -> AirCatStatsSnapshot {
        let (active_snapshots, active_home_sessions, cached_digests, revoked_members_cached) =
            if let Ok(mut inner) = self.inner.lock() {
                Self::prune(&mut inner, now_ms);
                (
                    inner.snapshots.len(),
                    inner.home_sessions.len(),
                    inner.digest_cache.len(),
                    inner.revoked_members.len(),
                )
            } else {
                (0, 0, 0, 0)
            };
        AirCatStatsSnapshot {
            active_snapshots,
            active_home_sessions,
            cached_digests,
            revoked_members_cached,
            downloads_started: self.downloads_started.load(Ordering::Relaxed),
            bytes_served: self.bytes_served.load(Ordering::Relaxed),
            digest_cache_hits: self.digest_cache_hits.load(Ordering::Relaxed),
            midstream_revocations: self.midstream_revocations.load(Ordering::Relaxed),
            tls_rejections: self.tls_rejections.load(Ordering::Relaxed),
        }
    }

    /// Explicit Home revocation invalidates all sessions for a destination.
    /// The caller must still consult the authoritative Home revocation roster
    /// at each file/stream request; this map is a cache, NOT the authority.
    pub fn revoke_member(&self, member: &str) {
        if let Ok(mut inner) = self.inner.lock() {
            if inner.revoked_members.len() < MAX_DIGEST_CACHE {
                inner.revoked_members.insert(member.to_string());
            }
            inner.nonces.retain(|(id, _), _| id != member);
            inner
                .snapshots
                .retain(|_, s| s.authenticated_destination_michi_id != member);
            inner.home_sessions.retain(|_, (id, _)| id != member);
        }
    }

    fn prune(inner: &mut Inner, now_ms: i64) {
        inner.nonces.retain(|_, expires| *expires > now_ms);
        inner.snapshots.retain(|_, s| s.expires_at_ms > now_ms);
        inner
            .home_challenges
            .retain(|_, c| c.expires_at_ms > now_ms);
        inner.home_sessions.retain(|_, (_, exp)| *exp > now_ms);
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::aircat_grants::{FileItem, Intent};
    fn fixture() -> (AirCatProducerSecurityState, Request) {
        let m = Manifest {
            manifest_version: 1,
            transfer_id: "tx".into(),
            source_device_id: "source".into(),
            total_tracks: 1,
            total_bytes: 6,
            items: vec![FileItem {
                logical_track_id: "l".into(),
                remote_track_id: "r".into(),
                title: "song".into(),
                artist: "artist".into(),
                album: "album".into(),
                format: "flac".into(),
                size: 6,
                sha256: "a".repeat(64),
            }],
        };
        let hash = manifest_sha256(&m).unwrap();
        let state = AirCatProducerSecurityState::new();
        state
            .record_producer_snapshot(
                ProducerSnapshot {
                    manifest: m.clone(),
                    manifest_sha256: hash.clone(),
                    authenticated_destination_michi_id: "member".into(),
                    expires_at_ms: 1_500_000,
                    originals: vec![OriginalAssetRevision {
                        remote_track_id: "r".into(),
                        exact_size: 6,
                        exact_sha256: "a".repeat(64),
                        strong_etag: format!("\"sha256-{}-6\"", "a".repeat(64)),
                        dev_ino: None,
                        modified_unix_ns: None,
                    }],
                },
                1_000_000,
            )
            .unwrap();
        let req = Request {
            intent: Intent {
                transfer_id: "tx".into(),
                source_michi_id: "source".into(),
                destination_michi_id: "member".into(),
                source_library_id: "lib".into(),
                destination_library_id: "dst".into(),
                selection_scope: "ALBUMS".into(),
                manifest_version: 1,
                required_scopes: vec!["content:read".into(), "content:transfer".into()],
                expires_at: 1_500_000,
                signed_grant: None,
                authorization_nonce_base64_url: String::new(),
            },
            manifest: m,
            manifest_sha256: hash,
            client_nonce_base64_url: URL_SAFE_NO_PAD.encode([7u8; 24]),
        };
        (state, req)
    }
    #[test]
    fn nonce_is_reserved_once_per_member() {
        let (s, r) = fixture();
        assert!(s.reserve_authorization(&r, "member", 1_000_010).is_ok());
        assert!(s.reserve_authorization(&r, "member", 1_000_011).is_err());
    }
    #[test]
    fn wrong_member_or_modified_catalog_never_reserved() {
        let (s, mut r) = fixture();
        assert!(s.reserve_authorization(&r, "attacker", 1_000_010).is_err());
        r.manifest.items[0].title = "mutated".into();
        r.manifest_sha256 = manifest_sha256(&r.manifest).unwrap();
        assert!(s.reserve_authorization(&r, "member", 1_000_011).is_err());
    }
    #[test]
    fn revoked_member_cannot_reuse_snapshot() {
        let (s, r) = fixture();
        s.revoke_member("member");
        assert!(s.reserve_authorization(&r, "member", 1_000_010).is_err());
        assert!(s
            .selected_original("tx", &r.manifest_sha256, "member", "r", 1_000_011)
            .is_err());
    }
}
